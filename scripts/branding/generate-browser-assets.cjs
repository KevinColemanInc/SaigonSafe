const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");
const brand = require("./saigonsafe.cjs");
const root = path.resolve(__dirname, "../..");
const manifestPath = "libs/assets/saigonsafe/browser-assets.json";
const sourcePaths = [
  "scripts/branding/saigonsafe.cjs",
  "scripts/branding/generate-browser-assets.cjs",
];
const hash = (data) => crypto.createHash("sha256").update(data).digest("hex");
const read = (file) => fs.readFileSync(path.join(root, file));
const write = (file, data) => {
  fs.mkdirSync(path.dirname(path.join(root, file)), { recursive: true });
  fs.writeFileSync(path.join(root, file), data);
};

async function main() {
  if (process.argv.includes("--check")) {
    const manifest = JSON.parse(read(manifestPath));
    for (const entry of [...manifest.sources, ...manifest.outputs]) {
      if (hash(read(entry.path)) !== entry.sha256) {
        throw new Error(`Stale SaigonSafe artwork: ${entry.path}. Regenerate browser assets.`);
      }
    }
    console.log(`SaigonSafe branding verified: ${manifest.outputs.length} assets.`);
    return;
  }

  const prettier = require("prettier");
  const options = await prettier.resolveConfig(path.join(root, "package.json"));
  const outputs = [];
  const record = (file, extra = {}) =>
    outputs.push({ path: file, sha256: hash(read(file)), ...extra });
  const save = async (file, content) => {
    const formatted = await prettier.format(content, {
      ...options,
      filepath: path.join(root, file),
    });
    write(file, formatted);
    record(file);
  };
  const raw = (file, content) => {
    write(file, content);
    record(file);
  };
  const componentSvg = (file, name, svg) => {
    for (const [token, value] of Object.entries(brand.colors)) {
      svg = svg.replaceAll(`="${value}"`, `="var(--saigonsafe-${token}, ${value})"`);
    }
    return save(
      file,
      `// Generated by scripts/branding/generate-browser-assets.cjs.\nimport { svg } from "../svg";\nexport const ${name} = svg\`${svg}\`;\n`,
    );
  };

  // Keep upstream symbol names as compatibility aliases; the actual artwork is SaigonSafe.
  const themedWordmark = brand
    .wordmark()
    .replace(
      `fill="${brand.colors.ink}"`,
      'fill="var(--saigonsafe-wordmark, rgb(var(--color-text-main)))"',
    );
  await componentSvg(
    "libs/assets/src/svg/svgs/saigonsafe-logo.ts",
    "SaigonSafeLogo",
    themedWordmark,
  );
  await componentSvg(
    "libs/assets/src/svg/svgs/saigonsafe-icon.ts",
    "SaigonSafeIcon",
    brand.mark().replace('width="64" height="64"', 'width="20" height="20"'),
  );
  await save(
    "libs/assets/src/svg/svgs/bitwarden-logo.icon.ts",
    'export { SaigonSafeLogo as BitwardenLogo } from "./saigonsafe-logo";\n',
  );
  await save(
    "libs/assets/src/svg/svgs/bitwarden-logo-beta.icon.ts",
    'export { SaigonSafeLogo as BitwardenLogoBeta } from "./saigonsafe-logo";\n',
  );
  await save(
    "libs/assets/src/svg/svgs/bitwarden-icon.ts",
    'export { SaigonSafeIcon as BitwardenIcon } from "./saigonsafe-icon";\n',
  );
  await save(
    "libs/assets/src/svg/svgs/shield.ts",
    'export { SaigonSafeIcon as BitwardenShield } from "./saigonsafe-icon";\n',
  );
  await save(
    "apps/browser/src/autofill/utils/saigonsafe-icons.ts",
    `// Generated by scripts/branding/generate-browser-assets.cjs.\nexport const logoIcon = ${JSON.stringify(brand.mark())};\nexport const logoLockedIcon = ${JSON.stringify(brand.mark({ locked: true }))};\n`,
  );
  raw("libs/assets/saigonsafe/logo.svg", brand.mark());
  raw("libs/assets/saigonsafe/wordmark.svg", brand.wordmark());

  const litBase = "apps/browser/src/autofill/content/components/";
  await save(
    `${litBase}icons/shield.ts`,
    `
    // Generated SaigonSafe mark. The Shield export remains for compatibility.
    import { html } from "lit";

    import { IconProps } from "../common-types";
    export function Shield({ ariaHidden = true, color }: IconProps) {
      return html\`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" fill="none" aria-hidden="\${ariaHidden}">
        <rect x="2" y="2" width="60" height="60" rx="18" fill="${brand.colors.jade}"/>
        <path d="${brand.sPath}" stroke="\${color || brandCream}" stroke-width="7" stroke-linecap="round"/>
        <circle cx="49" cy="14" r="5" fill="${brand.colors.coral}"/>
      </svg>\`;
    }
    const brandCream = "${brand.colors.cream}";
  `,
  );
  for (const [kind, name] of [
    ["keyhole", "Keyhole"],
    ["celebrate", "Celebrate"],
  ]) {
    await save(
      `${litBase}illustrations/${kind}.ts`,
      `
      // Generated by scripts/branding/generate-browser-assets.cjs.
      import { html } from "lit";

      import { ThemeTypes } from "@bitwarden/common/platform/enums";

      import { IconProps } from "../common-types";
      export function ${name}({ theme }: IconProps) {
        return theme === ThemeTypes.Dark ? html\`${brand.illustration(kind, true)}\` : html\`${brand.illustration(kind, false)}\`;
      }
    `,
    );
  }

  const pngs = [];
  const png = (file, svg, width, height = width) => pngs.push({ file, svg, width, height });
  const images = "apps/browser/src/images/";
  for (const size of [16, 19, 32, 38, 48, 96, 128]) {
    png(`${images}icon${size}.png`, brand.mark(), size);
    png(`${images}icon${size}_gray.png`, brand.mark({ gray: true }), size);
    png(`libs/assets/saigonsafe/local-build/icon${size}.png`, brand.mark({ local: true }), size);
    png(
      `libs/assets/saigonsafe/local-build/icon${size}_gray.png`,
      brand.mark({ local: true, gray: true }),
      size,
    );
  }
  for (const size of [19, 38]) {
    png(`${images}icon${size}_locked.png`, brand.mark({ locked: true }), size);
    png(`${images}berry${size}.png`, brand.mark({ notification: true }), size);
    png(
      `libs/assets/saigonsafe/local-build/icon${size}_locked.png`,
      brand.mark({ local: true, locked: true }),
      size,
    );
    png(
      `libs/assets/saigonsafe/local-build/berry${size}.png`,
      brand.mark({ local: true, notification: true }),
      size,
    );
  }
  for (const locked of [false, true]) {
    for (const scale of [1, 2]) {
      png(
        `${images}icon18_safari${locked ? "_locked" : ""}${scale === 2 ? "@2x" : ""}.png`,
        brand.mark({ mono: true, locked }),
        18 * scale,
      );
    }
  }
  // Safari shares this source tree, so keep its packaged app icons consistent too.
  for (const size of [16, 32, 128]) {
    png(
      `apps/browser/src/safari/desktop/Assets.xcassets/AppIcon.appiconset/icon${size}.png`,
      brand.mark(),
      size,
    );
  }
  for (const light of [false, true]) {
    png(
      `apps/browser/src/popup/images/logo-${light ? "white" : "dark"}@2x.png`,
      brand.wordmark(light),
      568,
      86,
    );
  }
  for (const theme of ["light", "dark", "solarized"]) {
    raw(`apps/browser/src/popup/images/search-desktop-${theme}.svg`, brand.search(theme));
  }
  raw("apps/browser/src/popup/images/close-button-white.svg", brand.glyph("close", "#FFFFFF"));
  raw(`${images}close.svg`, brand.glyph("close"));
  raw(
    "apps/browser/src/popup/images/loading.svg",
    brand.wrap(
      `<circle cx="32" cy="32" r="22" stroke="#D7E5DC" stroke-width="5"/><path d="M32 10a22 22 0 0 1 22 22" stroke="${brand.colors.jade}" stroke-width="5" stroke-linecap="round"/>`,
    ),
  );
  png("apps/browser/src/popup/images/bwi-globe.png", brand.glyph("globe"), 19);
  png("apps/browser/src/popup/images/bwi-passkey.png", brand.glyph("passkey"), 38);
  for (const kind of ["generate_password", "update_login", "review_at-risk_logins"]) {
    for (const dark of [false, true]) {
      png(
        `${images}at-risk-password-carousel/${kind}.${dark ? "dark" : "light"}.png`,
        brand.carousel(kind, dark),
        864,
        573,
      );
    }
  }

  const browser = await require("playwright").chromium.launch({
    headless: true,
    ...(process.platform === "darwin"
      ? { executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome" }
      : {}),
  });
  try {
    const page = await browser.newPage({ deviceScaleFactor: 1 });
    for (const { file, svg, width, height } of pngs) {
      const source = `libs/assets/saigonsafe/browser/${file.includes("/local-build/") ? "local-build/" : ""}${path.basename(file, ".png")}.svg`;
      // Some Safari basenames overlap manifest icons, but their artwork is identical.
      if (!outputs.some((entry) => entry.path === source)) raw(source, svg);
      const encoded = await page.evaluate(
        async ({ svg, width, height }) => {
          const image = new Image();
          image.src = `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`;
          await image.decode();
          const canvas = document.createElement("canvas");
          canvas.width = width;
          canvas.height = height;
          canvas.getContext("2d").drawImage(image, 0, 0, width, height);
          return canvas.toDataURL("image/png").split(",")[1];
        },
        { svg, width, height },
      );
      const buffer = Buffer.from(encoded, "base64");
      if (buffer.readUInt32BE(16) !== width || buffer.readUInt32BE(20) !== height) {
        throw new Error(`Incorrect export dimensions: ${file}`);
      }
      write(file, buffer);
      record(file, { width, height, source });
    }
  } finally {
    await browser.close();
  }
  await save(
    manifestPath,
    JSON.stringify(
      {
        brand: "SaigonSafe",
        renderer: "Playwright Chromium / SVG",
        sources: sourcePaths.map((file) => ({ path: file, sha256: hash(read(file)) })),
        outputs,
      },
      null,
      2,
    ),
  );
  console.log(`Generated ${pngs.length} PNGs and SaigonSafe vector assets.`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
